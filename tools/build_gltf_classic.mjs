// Builds assets/vendor/gltf-classic.js: three's GLTFLoader and the meshopt decoder (the r149 examples, the version the page's CDN three is) bundled by
// esbuild into ONE classic script, so the page and the highlights' export worker (js/exportworker.ts, importScripts) load glTF the same way, with no
// importmap and no ES modules. The bundle does not contain three: `import ... from 'three'` is mapped to the global THREE the page already has, so the loader
// builds the game's own classes (two copies of three break instanceof). It sets one global, GLTFClassic = { GLTFLoader, MeshoptDecoder }, which js/glb.ts uses.
//   npm run build:vendor        (the output is committed, like any vendored script; rebuild it only when three is upgraded)
import { build } from 'esbuild';
import path from 'path'; import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const shim = { name: 'three-is-global', setup(b) {
  b.onResolve({ filter: /^three$/ }, () => ({ path: 'three', namespace: 'three-global' }));
  b.onLoad({ filter: /.*/, namespace: 'three-global' }, () => ({ contents: 'module.exports = globalThis.THREE;', loader: 'js' }));
} };
const res = await build({
  stdin: {
    contents: "import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';\nimport { MeshoptDecoder } from 'three/examples/jsm/libs/meshopt_decoder.module.js';\nglobalThis.GLTFClassic = { GLTFLoader, MeshoptDecoder };\n",
    resolveDir: ROOT, sourcefile: 'gltf-classic-entry.js',
  },
  bundle: true, format: 'iife', minify: true, target: 'es2020', plugins: [shim], write: false, legalComments: 'none',
  absWorkingDir: ROOT,
});
const { default: fs } = await import('fs');
const head = '// GENERATED by tools/build_gltf_classic.mjs (npm run build:vendor): three r149\'s GLTFLoader + meshopt decoder as a classic script on the global THREE. Do not edit.\n';
const out = path.join(ROOT, 'assets/vendor/gltf-classic.js');
fs.writeFileSync(out, head + res.outputFiles[0].text);
console.log('wrote', path.relative(ROOT, out), fs.statSync(out).size, 'B');
