// Packs the gun parts made in Blender (models/<id>/<id>.glb, see models/fal/build_fal.py) into js/authored.ts, data the gun
// recipes build from (js/gunmodels.ts: rifle()'s rcv 'fal'), the way traced outlines are js/guntraces.ts. A script, not a file
// fetched at run time: the recipes are synchronous, and the baker (tools/bake_models.mjs, its per-part packs) builds every build
// from them in node.
//   node tools/authored_pack.mjs            (every models/<id>/<id>.glb)
//
// Per gun: rig (the frame the recipe builds the other parts against: the root's extras.rig_json), info (extras.info_json:
// the factory build's anchors) and the meshes, each with its slot, its catalogue material, the part_<key> it sits in (with
// that part's pivot) and an optional role (extras.role: 'tube' = the barrel's run ahead of the gas block, set to the barrel's
// length). Positions are in the gun's frame (three's: x right, y up, z = -forward), int16 at 1/32767 m (0.03 mm); normals
// int8; indices uint16; all base64.
import fs from 'fs'; import path from 'path';
import { NodeIO } from '@gltf-transform/core';
import { ROOT } from './model_env.mjs';

const io = new NodeIO();
const out = {};
for (const id of fs.readdirSync(path.join(ROOT, 'models'))) {
  const file = path.join(ROOT, 'models', id, id + '.glb');
  if (!fs.existsSync(file)) continue;
  const doc = await io.read(file), roots = doc.getRoot().listScenes()[0].listChildren();
  if (roots.length !== 1 || roots[0].getName() !== id) throw new Error(`${file}: one root node named "${id}"`);
  const rx = roots[0].getExtras(), meshes = [];
  const b64 = (ta) => Buffer.from(ta.buffer, ta.byteOffset, ta.byteLength).toString('base64');
  const walk = (node, part) => {
    const name = node.getName(), ex = node.getExtras();
    if (name.startsWith('part_')) {
      const t = node.getWorldMatrix(); part = { key: ex.part || name.slice(5), at: [t[12], t[13], t[14]] };
    }
    const mesh = node.getMesh();
    if (mesh) {
      const W = node.getWorldMatrix();
      for (const prim of mesh.listPrimitives()) {
        const P = prim.getAttribute('POSITION'), Nm = prim.getAttribute('NORMAL'), I = prim.getIndices(), n = P.getCount();
        const p = new Int16Array(n * 3), nn = new Int8Array(n * 3), v = [0, 0, 0], w = [0, 0, 0];
        for (let i = 0; i < n; i++) {
          P.getElement(i, v);
          for (let a = 0; a < 3; a++) {
            const c = W[a] * v[0] + W[4 + a] * v[1] + W[8 + a] * v[2] + W[12 + a];
            if (Math.abs(c) >= 1) throw new Error(`${id}: a vertex ${c} m out: the packing holds +-1 m`);
            p[i * 3 + a] = Math.round(c * 32767);
          }
          if (Nm) { Nm.getElement(i, w); for (let a = 0; a < 3; a++) { const c = W[a] * w[0] + W[4 + a] * w[1] + W[8 + a] * w[2]; w[a] = c; } const l = Math.hypot(w[0], w[1], w[2]) || 1; for (let a = 0; a < 3; a++) nn[i * 3 + a] = Math.round((w[a] / l) * 127); }
        }
        const idx = I ? Uint16Array.from(I.getArray()) : Uint16Array.from({ length: n }, (_, i) => i);
        const e = { slot: ex.slot || 'base', mat: (prim.getMaterial() && prim.getMaterial().getName()) || 'black', p: b64(p), n: b64(nn), i: b64(idx) };
        if (part) { e.part = part.key; e.at = part.at.map((c) => +c.toFixed(5)); }
        if (ex.role) e.role = ex.role;
        meshes.push(e);
      }
    }
    for (const c of node.listChildren()) walk(c, part);
  };
  for (const c of roots[0].listChildren()) walk(c, null);
  out[id] = { src: `models/${id}/${id}.glb`, rig: JSON.parse(rx.rig_json || '{}'), info: JSON.parse(rx.info_json || '{}'), meshes };
  console.log(id, meshes.length, 'meshes');
}
const body = Object.entries(out).map(([id, g]) => `  ${id}: ${JSON.stringify(g)},`).join('\n');
fs.writeFileSync(path.join(ROOT, 'js/authored.ts'),
  `'use strict';\n// GENERATED by tools/authored_pack.mjs from models/<id>/<id>.glb (made in Blender): do not edit, rebuild the model and run it.\n` +
  `// The gun parts the recipes build from (js/gunmodels.ts); the format is in the tool's header.\n` +
  `/** One authored mesh: slot, catalogue material, the part_<key> it rides in and that part's pivot, a role, and base64 int16 positions / int8 normals / uint16 indices. */\n` +
  `interface AuthoredMesh { slot: string; mat: string; part?: string; at?: number[]; role?: string; p: string; n: string; i: string }\n` +
  `/** One authored gun: the frame its recipe builds the other parts against (rig), its factory anchors (info) and meshes. */\n` +
  `interface AuthoredGun { src: string; rig: Record<string, any>; info: Record<string, any>; meshes: AuthoredMesh[] }\n` +
  `{\nvar G_Authored: Record<string, AuthoredGun> = {\n${body}\n};\nG.Authored = G_Authored;\n}\ninterface GameModules { Authored: typeof G_Authored; }\n`);
console.log('wrote js/authored.ts', fs.statSync(path.join(ROOT, 'js/authored.ts')).size, 'B');
