// Checks glTF gun models against the model contract (js/glb.ts GUN_MODEL_CONTRACT, docs/models.md).
//   npm run check:models <file.glb ...>     lists what is missing or wrong in each model (exit 1 if any has errors)
//   npm run check:models -- --write         regenerates docs/gun-model-info.schema.json and the contract tables in docs/models.md
//   npm run check:models -- --selftest      the contract against everything derived from it: the committed schema and doc are
//                                           current, the contract's material names are the game's catalogue, the baked guns pass
// Run after `tsc` (the npm script does): it reads the compiled dist/js/glb.js, so it is the very validator the game uses.
import fs from 'fs'; import path from 'path';
import { ROOT, loadModels, loadGame } from './model_env.mjs';

const args = process.argv.slice(2), Models = loadModels();
const SCHEMA = path.join(ROOT, 'docs/gun-model-info.schema.json'), DOC = path.join(ROOT, 'docs/models.md');
const BEGIN = '<!-- contract:begin (generated by npm run check:models -- --write: edit js/glb.ts, not this) -->', END = '<!-- contract:end -->';
const schemaText = () => JSON.stringify(Models.infoSchema(), null, 2) + '\n';
const docWith = (doc) => { const a = doc.indexOf(BEGIN), b = doc.indexOf(END); if (a < 0 || b < 0) throw new Error('docs/models.md has no contract markers'); return doc.slice(0, a) + BEGIN + '\n' + Models.contractMarkdown() + '\n' + doc.slice(b); };

/** Validates one .glb's bytes; prints and returns the number of errors. */
export function checkBuffer(label, buf, id) {
  let rep;
  try { rep = Models.validate(Models.describeGltfJson(Models.glbJson(buf)), id); } catch (e) { rep = { errors: [String(e.message || e)], warnings: [] }; }
  for (const e of rep.errors) console.error(`${label}: ERROR ${e}`);
  for (const w of rep.warnings) console.warn(`${label}: warning ${w}`);
  return rep.errors.length;
}

if (args.includes('--write')) {
  fs.writeFileSync(SCHEMA, schemaText()); fs.writeFileSync(DOC, docWith(fs.readFileSync(DOC, 'utf8')));
  console.log('wrote docs/gun-model-info.schema.json and the contract section of docs/models.md');
} else if (args.includes('--selftest')) {
  let bad = 0; const fail = (m) => { bad++; console.error('FAIL ' + m); };
  const lf = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n'); // (a checkout may have CRLF)
  if (!fs.existsSync(SCHEMA) || lf(SCHEMA) !== schemaText()) fail('docs/gun-model-info.schema.json differs from js/glb.ts INFO_FIELDS: run npm run check:models -- --write');
  if (!fs.existsSync(DOC) || lf(DOC) !== docWith(lf(DOC))) fail('the contract tables in docs/models.md differ from js/glb.ts: run npm run check:models -- --write');
  const G = loadGame(), cat = Object.keys(G.GunModels.M).sort(), named = Object.keys(Models.contract.materials.names).sort();
  for (const k of cat) if (!named.includes(k)) fail(`material '${k}' is in G.GunModels.M but not in the contract's materials`);
  for (const k of named) if (!cat.includes(k)) fail(`material '${k}' is in the contract but not in G.GunModels.M`);
  for (const [k, m] of Object.entries(Models.contract.materials.names)) { const has = !!(G.GunModels.M[k] && G.GunModels.M[k]().bumpMap); if (has !== !!m.bump) fail(`material '${k}': the contract says bump=${m.bump || 'none'} but the catalogue ${has ? 'has' : 'has no'} a bump map`); }
  for (const sl of ['base', 'grip', 'stock', 'mag', 'barrel', 'handguard', 'muzzle', 'optic', 'slide']) if (!Models.contract.slots[sl]) fail(`slot '${sl}' missing from the contract`);
  const dir = path.join(ROOT, 'assets/models/guns'); let n = 0;
  if (fs.existsSync(dir)) for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.glb'))) { n++; if (checkBuffer(f, fs.readFileSync(path.join(dir, f)), f.replace(/\.glb$/, ''))) bad++; }
  console.log(bad ? `${bad} problem(s)` : `contract, schema, docs and ${n} baked guns agree`);
  process.exit(bad ? 1 : 0);
} else {
  const files = args.filter((a) => !a.startsWith('--'));
  if (!files.length) { console.error('usage: npm run check:models <file.glb ...> | -- --write | -- --selftest'); process.exit(2); }
  let bad = 0;
  for (const f of files) { const n = checkBuffer(path.basename(f), fs.readFileSync(f)); console.log(`${path.basename(f)}: ${n ? n + ' error(s)' : 'ok'}`); bad += n; }
  process.exit(bad ? 1 : 0);
}
